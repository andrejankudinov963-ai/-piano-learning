// Рендеринг списка уроков
function renderLessonList() {
    const container = document.getElementById('lessonList');
    if (!container) return;
    container.innerHTML = LESSONS.map(lesson => `
        <div class="lesson-card ${lesson.id === currentLessonId ? 'active' : ''}" onclick="openLesson(${lesson.id})">
            <span class="num">${lesson.id}</span>
            ${lesson.title}
        </div>
    `).join('');
}

// Открытие урока
function openLesson(id) {
    currentLessonId = id;
    renderLessonList();
    renderLessonDetail(id);
}

// Рендеринг деталей урока
function renderLessonDetail(id) {
    const container = document.getElementById('lessonDetail');
    const lesson = LESSONS.find(l => l.id === id);
    if (!lesson) return;

    container.innerHTML = `
        <h3 class="lesson-title">${lesson.id}. ${lesson.title}</h3>
        <div class="lesson-theory">${lesson.theory}</div>
        <ol class="lesson-steps">
            ${lesson.steps.map((step, index) => `
                <li class="${step.done ? 'done' : ''}" onclick="toggleStep(${id}, ${index})">
                    <span class="step-num">${index + 1}</span>
                    <span class="step-text">${step.text}</span>
                    <span class="step-status">${step.done ? '✅' : '⏳'}</span>
                </li>
            `).join('')}
        </ol>
        ${lesson.type === 'note' ? renderKeyboard(lesson.notes) : ''}
        ${lesson.type === 'chord' ? renderKeyboard(lesson.notes) : ''}
        ${lesson.type === 'scale' ? renderKeyboard(lesson.notes) : ''}
        ${lesson.type === 'rhythm' ? renderRhythmGrid() : ''}
        ${lesson.type === 'syncopation' ? renderSyncopationGrid() : ''}
        ${lesson.type === 'dynamic' ? renderDynamicExercise() : ''}
        ${lesson.type === 'posture' ? renderPostureDiagram() : ''}
        ${lesson.type === 'checklist' ? renderChecklist(lesson.steps) : ''}
        ${lesson.id >= 113 ? renderYoutubeEmbed() : ''}
    `;
}

